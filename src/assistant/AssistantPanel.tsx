function SourceList({ sources, lang }: { sources: AnswerSources; lang: 'en' | 'ar' }) {
  const { t } = useI18n();
  const none = !sources.verified;
  // One line per lesson, listing every cited page; the book title is shown once.
  const lessons: { unit: number; lesson: string | null; unitTitle: TextbookCitation['unitTitle']; lessonTitle: TextbookCitation['lessonTitle']; pages: number[] }[] = [];
  for (const c of sources.textbook) {
    const g = lessons.find((x) => x.unit === c.unit && x.lesson === c.lesson);
    if (g) g.pages = [...new Set([...g.pages, c.page])].sort((a, b) => a - b);
    else lessons.push({ unit: c.unit, lesson: c.lesson, unitTitle: c.unitTitle, lessonTitle: c.lessonTitle, pages: [c.page] });
  }
  return (
    <div className="assistant-sources" data-testid="assistant-sources">
      <div className="assistant-source-chips">
        {sources.textbook.length > 0 && <span className={`chip ${sources.support === 'partial' ? 'chip-amber' : 'chip-green'}`}>{t(sources.support === 'partial' ? T.srcPartial : T.srcTextbook)}</span>}
        {sources.experiment && <span className="chip chip-navy">{t(T.srcExperiment)}</span>}
        {sources.general && <span className="chip chip-amber">{t(T.srcGeneral)}</span>}
        {none && <span className="chip">{t(T.srcUnknown)}</span>}
      </div>
      {sources.textbook.length > 0 && <p className="small muted assistant-citation">{sources.textbook[0].book[lang]}</p>}
      {lessons.map((g) => (
        <p key={`${g.unit}-${g.lesson}`} className="small muted assistant-citation">
          {t(T.unit)} {g.unit}: {g.unitTitle[lang]} ·{' '}
          {g.lesson ? (
            <>
              {t(T.lesson)} <bdi dir="ltr">{g.lesson}</bdi>: {g.lessonTitle[lang]}
            </>
          ) : (
            g.lessonTitle[lang]
          )}{' '}
          · {t(g.pages.length > 1 ? T.pages : T.page)}{' '}
          <bdi dir="ltr">{g.pages.join(', ')}</bdi>
        </p>
      ))}
      {sources.experiment && (
        <p className="small muted assistant-citation">{t(sources.experimentCheck === 'consistent' ? T.expConsistent : T.expReported)}</p>
      )}
      {sources.experimentCheck === 'rejected' && <p className="small muted assistant-citation">{t(T.expRejected)}</p>}
      {!sources.textbook.length && sources.verified && <p className="small muted assistant-citation">{t(T.noTextbook)}</p>}
    </div>
  );
}

function recordsText(s: AssistantSnapshot) {
  if (!s.records.length || !s.columns) return '';
  const head = s.columns.map((c) => `${c.label.en} (${c.unit})`).join(' | ');
  const rows = s.records.slice(-12).map((r) => s.columns!.map((c) => fmt(r.values[c.id], 4)).join(' | '));
  return [head, ...rows].join('\n');
}

export function AssistantPanel({ snapshot, onClose }: { snapshot: AssistantSnapshot; onClose: () => void }) {
  const { t, lang } = useI18n();
  const [status, setStatus] = useState<Status>(null);
  const [log, setLog] = useState<AssistantReply[]>([]);
  const [busy, setBusy] = useState(false);
  const [question, setQuestion] = useState('');
  const [shown, setShown] = useState<Record<string, boolean>>({});
  const endRef = useRef<HTMLDivElement>(null);

  useEffect(() => {
    fetchAssistantStatus().then(setStatus);
  }, []);
  useEffect(() => {
    endRef.current?.scrollIntoView?.({ block: 'end' });
  }, [log, busy]);

  const live = !!status?.available;

  const ask = async (intent: Intent, q?: string) => {
    const id = `${Date.now()}-${Math.random().toString(36).slice(2, 7)}`;
    if (live) {
      let busy429 = false;
      setBusy(true);
      try {
        const history = log.slice(-4).flatMap((m) => [
          { role: 'user', content: m.question ?? m.intent },
          { role: 'assistant', content: m.text },
        ]);
        const res = await fetch('/api/assistant', {
          method: 'POST',
          headers: { 'Content-Type': 'application/json' },
          signal: AbortSignal.timeout(60_000),
          body: JSON.stringify({
            lab: snapshot.lab,
            intent,
            lang,
            activity: snapshot.activity ? `${snapshot.activity.title.en} — ${snapshot.activity.ref.en}` : '',
            hint: snapshot.activity ? `${snapshot.activity.title.ar} ${snapshot.activity.title.en}` : '',
            curriculum: CONTEXT[snapshot.lab].assistantContext,
            state: snapshot.stateText,
            records: recordsText(snapshot),
            question: q ?? '',
            history,
          }),
        });
        const data = res.ok ? await res.json() : null;
        if (!res.ok) busy429 = res.status === 429 || (await res.json().catch(() => null))?.category === 'rate_limited';
        if (data?.refused) {
          setLog((x) => [...x, { id, intent, text: t(T.refused), source: 'ai', question: q }]);
        } else if (data?.text) {
          setLog((x) => [...x, { id, intent, text: data.text, source: 'ai', sources: data.sources, question: q }]);
        } else throw new Error('no text');
      } catch {
        const out = offlineReply(intent, snapshot, lang, q);
        setLog((x) => [...x, { id, intent, text: `${t(busy429 ? T.errorBusy : T.error)}\n\n${out.text}`, answer: out.answer, source: 'offline', question: q }]);
      } finally {
        setBusy(false);
      }
      return;
    }
    const out = offlineReply(intent, snapshot, lang, q);
    setLog((x) => [...x, { id, intent, text: out.text, answer: out.answer, source: 'offline', question: q }]);
  };

  const intents: Intent[] = ['explain', 'why', 'next', 'practice', 'interpret'];

  return (
    <aside className="assistant-dock" aria-label={t(T.title)} onKeyDown={(e) => e.key === 'Escape' && onClose()}>
      <div className="assistant-head">
        <div>
          <h2>
            <Icon name="sparkle" /> {t(T.title)}
          </h2>
          {status && (
            <span className={`chip ${live ? 'chip-primary' : 'chip-amber'}`} data-testid="assistant-mode">
              {live ? t(T.liveLabel, { name: providerName(status) }) : t(T.offlineLabel)}
            </span>
          )}
        </div>
        <button type="button" className="btn btn-ghost btn-sm" onClick={onClose} aria-label={t(UI.close)}>
          <Icon name="close" />
        </button>
      </div>
      <p className="small muted">{status ? (live ? t(T.liveNote, { name: providerName(status) }) : t(T.offlineNote)) : ''}</p>
      {live && status?.textbook && !status.textbook.available && (
        <p className="small muted" data-testid="assistant-no-index">
          {t(T.noIndex)}
        </p>
      )}
      <div className="assistant-intents">
        {intents.map((i) => (
          <button key={i} type="button" className="btn btn-sm" disabled={busy} onClick={() => ask(i)}>
            {t(T[i])}
          </button>
        ))}
      </div>
      <div className="assistant-log" aria-live="polite">
        {log.length === 0 && <p className="empty-state">{t(T.empty)}</p>}
        {log.map((m) => (
          <div key={m.id} className="assistant-msg">
            <div className="assistant-msg-head">
              <span className="small muted">{m.question ? `“${m.question}”` : t(T[m.intent])}</span>
              <span className={`chip ${m.source === 'ai' ? 'chip-primary' : 'chip-amber'}`}>{m.source === 'ai' ? t(T.sourceAi) : t(T.sourceOffline)}</span>
            </div>
            <p style={{ whiteSpace: 'pre-wrap' }}>{m.text}</p>
            {m.source === 'ai' && m.sources && <SourceList sources={m.sources} lang={lang} />}
            {m.source === 'offline' && <p className="small muted assistant-citation">{t(T.srcOffline)}</p>}
            {m.answer &&
              (shown[m.id] ? (
                <p className="fb fb-explain ltr" style={{ display: 'block' }}>
                  {m.answer}
                </p>
              ) : (
                <button type="button" className="btn btn-sm btn-ghost" onClick={() => setShown((s) => ({ ...s, [m.id]: true }))}>
                  {t(T.showAnswer)}
                </button>
              ))}
          </div>
        ))}
        {busy && <p className="small muted">{t(T.thinking)}</p>}
        <div ref={endRef} />
      </div>
      <form
        className="assistant-ask"
        onSubmit={(e) => {
          e.preventDefault();
          if (!question.trim()) return;
          const q = question.trim();
          setQuestion('');
          ask('ask', q);
        }}
      >
        <input type="text" value={question} onChange={(e) => setQuestion(e.target.value)} placeholder={t(T.ask)} aria-label={t(T.ask)} maxLength={500} />
        <button type="submit" className="btn btn-navy btn-sm" disabled={busy || !question.trim()}>
          <Icon name="send" className="flip-rtl" /> {t(T.send)}
        </button>
      </form>
    </aside>
  );
}
