type Status = { available: boolean; provider?: 'gemini' | 'claude' | null; model: string | null; textbook?: { available: boolean } } | null;

/** Display name of the AI service behind the live assistant. */
export const providerName = (s: Status) => (s?.provider === 'gemini' ? 'Google Gemini' : 'Claude');
let statusPromise: Promise<Status> | null = null;
/** Forget the cached server status (used by tests). */
export const resetAssistantStatus = () => {
  statusPromise = null;
};
export function fetchAssistantStatus(): Promise<Status> {
  statusPromise ??= fetch('/api/assistant/status')
    .then((r) => (r.ok ? r.json() : { available: false, model: null }))
    .catch(() => ({ available: false, model: null }));
  return statusPromise;
}

